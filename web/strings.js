  function russianText(en) {
    if (Object.prototype.hasOwnProperty.call(russian, en)) return russian[en];
    var m = /^(\d+) hours ago$/.exec(en);
    if (m) return m[1] + ' ч назад';
    m = /^(\d+) (min|h) ago$/.exec(en);
    if (m) return m[1] + (m[2] === 'min' ? ' мин назад' : ' ч назад');
    m = /^The App Dock holds up to (\d+) apps\.$/.exec(en);
    if (m) return 'На панель приложений можно добавить не более ' + m[1] + ' приложений.';
    m = /^What's (.+) singing\?$/.exec(en);
    if (m) return 'Что поёт ' + m[1] + '?';
    m = /^(.+)'s up!$/.exec(en);
    if (m) return 'Очередь: ' + m[1] + '!';
    m = /^Starting in (\d+)$/.exec(en);
    if (m) return 'Начало через ' + m[1];
    return en;
  }

  function detect(setting) {
    var v = (setting || 'auto').toLowerCase();
    if (v === 'auto') v = (navigator.language || 'en').toLowerCase();
    return v.indexOf('ru') === 0 ? 'ru' : v.indexOf('de') === 0 ? 'de' : v.indexOf('pt') === 0 ? 'pt' : v.indexOf('es') === 0 ? 'es' : 'en';
  }

