  function germanText(en) {
    if (Object.prototype.hasOwnProperty.call(german, en)) return german[en];
    var m = /^(\d+) hours ago$/.exec(en);
    if (m) return 'Vor ' + m[1] + ' Stunden';
    m = /^(\d+) (min|h) ago$/.exec(en);
    if (m) return 'vor ' + m[1] + (m[2] === 'min' ? ' Min.' : ' Std.');
    m = /^(\d+) seasons?$/.exec(en);
    if (m) return m[1] + (m[1] === '1' ? ' Staffel' : ' Staffeln');
    m = /^H:(\S+)(\s+)L:(\S+)$/.exec(en);
    if (m) return 'H:' + m[1] + m[2] + 'T:' + m[3];
    m = /^The App Dock holds up to (\d+) apps\.$/.exec(en);
    if (m) return 'Ins App-Dock passen bis zu ' + m[1] + ' Apps.';
    m = /^What's (.+) singing\?$/.exec(en);
    if (m) return 'Was singt ' + m[1] + '?';
    m = /^(.+)'s up!$/.exec(en);
    if (m) return m[1] + ' ist dran!';
    m = /^Starting in (\d+)$/.exec(en);
    if (m) return 'Startet in ' + m[1];
    return en;
  }

